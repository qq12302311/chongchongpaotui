/**
 * 获取区县对应的地级市
 * @param {string} district 区县名称
 * @returns {string} 地级市名称，如果找不到则返回原区县名称
 */
export function getDistrictCity(district) {
  return districtToCityMap[district] || district;
}

/**
 * 批量获取区县对应的地级市
 * @param {Array} districts 区县名称数组
 * @returns {Object} 以地级市为key，区县数组为value的对象
 */
export function groupDistrictsByCity(districts) {
  if (!districts || !Array.isArray(districts)) {
    return {};
  }

  const grouped = {};
  
  districts.forEach(district => {
    const cityName = getDistrictCity(district);
    
    if (!grouped[cityName]) {
      grouped[cityName] = [];
    }
    
    grouped[cityName].push(district);
  });

  return grouped;
}
